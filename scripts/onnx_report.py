"""Write docs/results/week3_onnx.md from the step 1 run outputs (no number typed by hand).

Reads from ``--runs`` (default ``../legacy/runs/week3``): ``benchmark_irra.json``,
``model_eval_v2.json``, ``profile_case2_torch_240_t2.json``,
``profile_case2_int8_240_t2.json``; and ``--week2`` ``model_eval.json`` for irra-v1.

Usage::

    python scripts/onnx_report.py
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

from person_search.eval.gate import compare_versions


def load(p: Path) -> dict:
    return json.loads(p.read_text())


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--runs", type=Path, default=Path("../legacy/runs/week3"))
    ap.add_argument("--week2", type=Path, default=Path("../legacy/runs/week2"))
    ap.add_argument("--out", type=Path, default=Path("docs/results/week3_onnx.md"))
    args = ap.parse_args()
    bench = load(args.runs / "benchmark_irra.json")
    v1 = load(args.week2 / "model_eval.json")["versions"]["irra-v1"]
    v2 = load(args.runs / "model_eval_v2.json")["versions"]["irra-v2"]
    pt = load(args.runs / "profile_case2_torch_240_t2.json")
    q8 = load(args.runs / "profile_case2_int8_240_t2.json")
    failures = compare_versions(v1, v2)

    md = [
        "# Week 3, step 1: IRRA image tower in ONNX INT8",
        "",
        f"Machine: {bench['machine']['platform']}, {bench['machine']['cpu_count']} vCPU "
        "(Intel Xeon with AVX-512 VNNI, which runs INT8 dot products natively), "
        f"{bench['threads']} threads for every backend. Generated by `scripts/onnx_report.py`.",
        "",
        "## Speed of the image tower alone",
        "",
        "Real person crops (test case 2), warm-up then repeated runs.",
        "",
        "| Backend | Size | Batch 1 p50 / p95 | Batch 32 p50 / p95 | ms per crop (batch 32) "
        "| Speed-up (batch 32) |",
        "|---|---:|---:|---:|---:|---:|",
    ]
    for name, r in bench["backends"].items():
        b1, b32 = r["batch1"], r["batch32"]
        md.append(
            f"| {name} | {r['size_mb']:.0f} MB | {b1['p50_ms']:.0f} / {b1['p95_ms']:.0f} ms "
            f"| {b32['p50_ms']:.0f} / {b32['p95_ms']:.0f} ms | {b32['ms_per_crop']:.0f} "
            f"| {r['speedup_batch32']:.2f}x |"
        )
    m1, m2 = v1["metrics"], v2["metrics"]
    md += [
        "",
        "ONNX FP32 is no faster than PyTorch; the gain comes from INT8.",
        "",
        "## Accuracy on the gate set (irra-v1 = PyTorch FP32, irra-v2 = ONNX INT8)",
        "",
        "| Metric | irra-v1 | irra-v2 | Change |",
        "|---|---:|---:|---:|",
    ]
    for key, label, fmt in (
        ("campus_mAP_cosine", "Image tower campus mAP", "pct"),
        ("campus_rank1_cosine", "Image tower campus Rank-1", "pct"),
        ("text_hit1_count", "Text Hit@1 (12 descriptions)", "count"),
        ("text_hit5_count", "Text Hit@5", "count"),
        ("text_mrr", "Text MRR", "f3"),
    ):
        a, b = m1[key], m2[key]
        if fmt == "pct":
            md.append(f"| {label} | {a:.2%} | {b:.2%} | {100 * (b - a):+.2f} pts |")
        elif fmt == "count":
            md.append(f"| {label} | {a}/12 | {b}/12 | {b - a:+d} |")
        else:
            md.append(f"| {label} | {a:.3f} | {b:.3f} | {b - a:+.3f} |")
    same_top = sum(
        x["top"][0]["track"] == y["top"][0]["track"]
        for x, y in zip(v1["details"]["text"], v2["details"]["text"], strict=True)
    )
    md += [
        "",
        f"Same top-ranked track for {same_top} of 12 descriptions. "
        f"Gate verdict (decision 0010 rules): **{'PASSED' if not failures else 'BLOCKED'}**"
        + ("" if not failures else ": " + "; ".join(failures))
        + ".",
        "",
        "## End-to-end ingest (test case 2, first 240 sampled frames, 2 threads)",
        "",
        "| Stage | PyTorch IRRA | ONNX INT8 IRRA |",
        "|---|---:|---:|",
    ]
    for stage in ("embed:irra", "embed:osnet", "track", "detect", "decode"):
        a, b = pt["stages"][stage], q8["stages"][stage]
        extra_a = f" ({a['ms_per_crop']:.0f} ms/crop)" if "ms_per_crop" in a else ""
        extra_b = f" ({b['ms_per_crop']:.0f} ms/crop)" if "ms_per_crop" in b else ""
        md.append(f"| {stage} | {a['seconds']:.1f} s{extra_a} | {b['seconds']:.1f} s{extra_b} |")
    md += [
        f"| **wall time** | **{pt['wall_seconds']:.0f} s** ({pt['samples_per_s']} frames/s) "
        f"| **{q8['wall_seconds']:.0f} s** ({q8['samples_per_s']} frames/s) |",
        "",
        f"Ingest is {pt['wall_seconds'] / q8['wall_seconds']:.2f}x faster with INT8 IRRA. Same "
        f"observations ({q8['observations']:,}) and tracks ({q8['tracks']}) in both runs: "
        "detection and tracking are untouched.",
        "OSNet is now the largest stage, and it is slower on 2 threads than it was on 1 "
        "(104 ms per crop in Week 2): see AUDIT.md F28.",
        "",
    ]
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(md))
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
